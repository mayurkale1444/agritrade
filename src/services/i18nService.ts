const LANG_STORAGE_KEY = 'agritrade_preferred_lang';

export function getSavedLanguage(): SupportedLanguage {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY) as SupportedLanguage;
    if (saved && (saved === 'mr' || saved === 'hi' || saved === 'en' || saved === 'ta' || saved === 'kn')) {
      return saved;
    }
  } catch {
    // Local storage access issue
  }
  return 'mr'; // Default to Marathi for Maharashtra agricultural focus
}

export function saveLanguage(lang: SupportedLanguage): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // Ignore storage quota
  }
}

export function t(key: keyof TranslationDictionary, lang: SupportedLanguage = 'mr'): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.mr;
  return (dict[key] as string) || (TRANSLATIONS.mr[key] as string) || '';
}

